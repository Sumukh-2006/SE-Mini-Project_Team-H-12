#pragma once
#include <sqlite3.h>
#include <string>

namespace hms {
/**
 * @brief RAII wrapper managing the lifecycle of an SQLite prepared statement.
 *
 * Encapsulates an sqlite3_stmt handle and guarantees resource finalization upon destruction.
 * Requires all dynamic user input to be bound via parameterized queries to prevent SQL injection.
 */
class Statement {
  sqlite3_stmt *stmt_ = nullptr;

public:
  /**
   * @brief Compiles a SQL query into an SQLite prepared statement.
   *
   * @param db Pointer to the active SQLite database connection.
   * @param sql SQL query string containing parameter placeholders.
   * @throws std::runtime_error If statement preparation fails or SQL syntax is invalid.
   */
  Statement(sqlite3 *db, const std::string &sql);

  /**
   * @brief Finalizes the prepared statement and releases allocated SQLite resources.
   */
  ~Statement();

  Statement(const Statement &) = delete;
  Statement &operator=(const Statement &) = delete;

  /**
   * @brief Binds a string parameter to a 1-based placeholder index.
   *
   * @param index 1-based index of the SQL parameter placeholder (?).
   * @param value String value to bind to the statement.
   * @throws std::runtime_error If parameter binding fails.
   */
  void bind(int index, const std::string &value);

  /**
   * @brief Binds an integer parameter to a 1-based placeholder index.
   *
   * @param index 1-based index of the SQL parameter placeholder (?).
   * @param value Integer value to bind to the statement.
   * @throws std::runtime_error If parameter binding fails.
   */
  void bind(int index, int value);

  /**
   * @brief Advances statement evaluation to the next result row.
   *
   * @return true If a new row of data is available (SQLITE_ROW).
   * @return false If statement execution completed without further rows (SQLITE_DONE).
   * @throws std::runtime_error If step execution encounters an error or constraint violation.
   */
  bool step();

  /**
   * @brief Retrieves the text content of a 0-based column from the current row.
   *
   * @param column 0-based index of the column to read.
   * @return std::string Column text value, or empty string if NULL.
   */
  std::string text(int column) const;

  /**
   * @brief Retrieves the integer value of a 0-based column from the current row.
   *
   * @param column 0-based index of the column to read.
   * @return int 32-bit integer column value.
   */
  int integer(int column) const;
};

/**
 * @brief Owns a SQLite connection and initializes its schema and pragmas.
 *
 * File databases require WAL journaling and synchronous=FULL; foreign keys
 * enforce relational consistency. FULL requests durable commits from SQLite
 * (subject to the filesystem and storage honoring synchronization requests).
 * In-memory databases use SQLite's memory journal and have no crash durability.
 */
class Database {
  sqlite3 *db_ = nullptr;

public:
  /**
   * @brief Opens or creates an SQLite database at the specified path and initializes schema.
   *
   * Automatically creates parent directories for file-backed databases, configures WAL mode,
   * synchronous=FULL, and foreign key enforcement, then executes idempotent table migrations.
   *
   * @param path Filesystem path to SQLite database file or ":memory:" for an in-memory database.
   * @throws std::runtime_error If database opening, pragma configuration, or schema initialization fails.
   */
  explicit Database(const std::string &path);

  /**
   * @brief Closes the SQLite database connection and releases allocated resources.
   */
  ~Database();

  Database(const Database &) = delete;
  Database &operator=(const Database &) = delete;

  /**
   * @brief Compiles a SQL query into an executable prepared Statement object.
   *
   * @param sql SQL statement string with optional parameter placeholders.
   * @return Statement Compiled Statement object wrapping the SQLite statement handle.
   * @throws std::runtime_error If statement preparation fails.
   */
  Statement prepare(const std::string &sql);

  /**
   * @brief Executes a parameterless SQL command string directly against the database.
   *
   * @param sql SQL command string to execute.
   * @throws std::runtime_error If SQLite execution encounters an error.
   */
  void execute(const std::string &sql);

  /**
   * @brief Retrieves the row ID generated by the most recent successful INSERT statement.
   *
   * @return int Autoincrement primary key ID of the inserted record.
   */
  int lastId() const;
};

/**
 * @brief Non-copyable RAII owner of a BEGIN IMMEDIATE transaction.
 *
 * SQLite supplies atomicity and writer isolation; constraints and business
 * validation supply consistency. commit() marks success only after COMMIT
 * succeeds. Scope exit rolls back pending writes, including exception unwinding.
 * SIGKILL/power loss cannot run destructors: SQLite WAL recovery ignores
 * uncommitted frames and preserves fully synchronized committed transactions.
 * The Database must outlive this guard; nested transactions are unsupported.
 */
class Transaction {
  Database &db_;
  bool committed_ = false;

public:
  /**
   * @brief Begins an immediate SQLite transaction (BEGIN IMMEDIATE).
   *
   * Acquires the database writer lock immediately to ensure writer isolation
   * and prevent concurrency deadlocks.
   *
   * @param db Reference to the Database instance managing the transaction.
   * @throws std::runtime_error If beginning the transaction fails.
   */
  explicit Transaction(Database &db);

  /**
   * @brief Destructor that rolls back uncommitted operations upon scope exit (ROLLBACK).
   *
   * Guarantees exception safety and state rollback upon scope exit or unwinding;
   * no-op if commit() was previously invoked.
   */
  ~Transaction() noexcept;

  Transaction(const Transaction &) = delete;
  Transaction &operator=(const Transaction &) = delete;

  /**
   * @brief Commits all pending changes executed within this transaction (COMMIT).
   *
   * Atomically finalizes transaction writes in the database and disarms automatic rollback.
   *
   * @throws std::runtime_error If the COMMIT operation fails.
   */
  void commit();
};
} // namespace hms
